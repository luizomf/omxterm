// Regenerates every application icon derivative from the one scalable source,
// src/shared/icons/hicolor/scalable/apps/omxterm-hero.svg:
//
//   assets/application-icon.svg          copy of the source
//   assets/application-icon.png          1024 px (window, About, Dock, builder)
//   assets/application-icon-macos.svg    artwork on the 1024 px macOS grid
//   assets/application-icon.icns         macOS 16-512 pt, standard and Retina
//   assets/icons/hicolor/...             Linux theme icons (16-512 px, SVG)
//   src/renderer/application-icon.ts     the SVG text for the startup screen
//
// The results are committed so packaging never needs image tooling. Run
// `node scripts/generate-application-icons.mjs` after changing the source; it
// needs rsvg-convert (librsvg).
import { execFile as execFileCallback } from "node:child_process";
import {
  copyFile,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFile = promisify(execFileCallback);
const root = path.resolve(import.meta.dirname, "..");
const source = path.join(
  root,
  "src/shared/icons/hicolor/scalable/apps/omxterm-hero.svg",
);
const assets = path.join(root, "assets");

// Apple's grid keeps the artwork inside an 824 px square on a 1024 px canvas.
const MAC_CANVAS = 1024;
const MAC_ARTWORK = 824;
// ICNS chunk types and their pixel sizes (iconutil's standard set).
const ICNS_TYPES = [
  ["ic04", 16],
  ["ic05", 32],
  ["ic11", 32],
  ["ic12", 64],
  ["ic07", 128],
  ["ic13", 256],
  ["ic08", 256],
  ["ic14", 512],
  ["ic09", 512],
  ["ic10", 1024],
];
const HICOLOR_SIZES = [16, 22, 24, 32, 48, 64, 128, 256, 512];

async function render(svg, size, output) {
  await execFile("rsvg-convert", [
    "--width",
    String(size),
    "--height",
    String(size),
    "--keep-aspect-ratio",
    "--output",
    output,
    svg,
  ]);
}

export function macosIconSvg(sourceSvg) {
  const open = sourceSvg.indexOf(">", sourceSvg.indexOf("<svg"));
  const close = sourceSvg.lastIndexOf("</svg>");
  const viewBox = /viewBox="([^"]+)"/u.exec(sourceSvg.slice(0, open))?.[1];
  if (open < 0 || close < 0 || !viewBox)
    throw new Error("The icon source is not a single SVG with a viewBox");
  const inset = (MAC_CANVAS - MAC_ARTWORK) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${MAC_CANVAS}" height="${MAC_CANVAS}" viewBox="0 0 ${MAC_CANVAS} ${MAC_CANVAS}"><svg x="${inset}" y="${inset}" width="${MAC_ARTWORK}" height="${MAC_ARTWORK}" viewBox="${viewBox}">${sourceSvg.slice(open + 1, close)}</svg></svg>\n`;
}

export function applicationIconModule(sourceSvg) {
  return `// Generated by scripts/generate-application-icons.mjs from
// src/shared/icons/hicolor/scalable/apps/omxterm-hero.svg. Do not edit.
export const applicationIconSvg = ${JSON.stringify(sourceSvg)};
`;
}

// ICNS: "icns", total length, then one (type, length, PNG data) chunk per size.
export function encodeIcns(chunks) {
  const parts = chunks.map(([type, png]) => {
    const header = Buffer.alloc(8);
    header.write(type, 0, "ascii");
    header.writeUInt32BE(png.length + 8, 4);
    return Buffer.concat([header, png]);
  });
  const header = Buffer.alloc(8);
  header.write("icns", 0, "ascii");
  header.writeUInt32BE(
    8 + parts.reduce((sum, part) => sum + part.length, 0),
    4,
  );
  return Buffer.concat([header, ...parts]);
}

async function main() {
  const sourceSvg = await readFile(source, "utf8");
  await mkdir(path.join(root, ".scratch"), { recursive: true });
  const work = await mkdtemp(path.join(root, ".scratch", "icons-"));
  try {
    await copyFile(source, path.join(assets, "application-icon.svg"));
    await render(source, 1024, path.join(assets, "application-icon.png"));

    const macos = path.join(assets, "application-icon-macos.svg");
    await writeFile(macos, macosIconSvg(sourceSvg));
    const chunks = [];
    for (const [type, size] of ICNS_TYPES) {
      const png = path.join(work, `${type}.png`);
      await render(macos, size, png);
      chunks.push([type, await readFile(png)]);
    }
    await writeFile(
      path.join(assets, "application-icon.icns"),
      encodeIcns(chunks),
    );

    const hicolor = path.join(assets, "icons", "hicolor");
    for (const size of HICOLOR_SIZES) {
      const directory = path.join(hicolor, `${size}x${size}`, "apps");
      await mkdir(directory, { recursive: true });
      await render(source, size, path.join(directory, "omxterm.png"));
    }
    // The renderer shows the icon while a window starts; esbuild needs no
    // extra loader for a TypeScript string module.
    await writeFile(
      path.join(root, "src/renderer/application-icon.ts"),
      applicationIconModule(sourceSvg),
    );
    const scalable = path.join(hicolor, "scalable", "apps");
    await mkdir(scalable, { recursive: true });
    await copyFile(source, path.join(scalable, "omxterm.svg"));
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename)
  await main();
