// Built-in Terminal Themes offered by Preferences. The default is OMXTerm's
// own omtheme; the others are AshyTerm's built-in color schemes
// (src/ashyterm/settings/colors.py at 8d50567e, MIT), converted to the
// Terminal Theme format. AshyTerm schemes have no selection colors, so the
// selection background mixes 30% of the foreground into the background.
import { DEFAULT_TERMINAL_THEME, type TerminalTheme } from "./terminal-theme";

export interface TerminalScheme {
  // Lowercase file-name-safe id; Preferences writes themes/<id>.json.
  readonly id: string;
  readonly theme: TerminalTheme;
}

const scheme = (
  id: string,
  name: string,
  colors: TerminalTheme["colors"],
): TerminalScheme =>
  Object.freeze({
    id,
    theme: Object.freeze({ version: 1, name, colors: Object.freeze(colors) }),
  });

